async (page) => {
  const checks = [], errors = []
  page.on('pageerror', error => errors.push(String(error)))
  const check = (condition, name) => {if(!condition)throw Error(name);checks.push(name)}
  await page.emulateMedia({reducedMotion:'no-preference'})
  await page.setViewportSize({width:1600,height:900})
  await page.goto('http://127.0.0.1:5175/?profile=1')
  await page.locator('#boot-intro[data-phase="access"]').waitFor()
  check(await page.locator('#home').getAttribute('inert') !== null,'Home input isolated during opening')
  check(await page.locator('[data-intro-skip]').isVisible(),'Skip control visible')
  await page.locator('#boot-intro[data-phase="logo"]').waitFor()
  await page.screenshot({path:'output/playwright/hansen/boot-logo.png'})
  await page.locator('#boot-intro[data-phase="auth"][data-resources="ready"]').waitFor()
  const frames = () => page.evaluate(()=>window.hansenProfile.scene.getStats().renderedFrames)
  const before = await frames()
  await page.waitForTimeout(450)
  check(await frames()===before,'No continuous 3D rendering behind opening')
  await page.screenshot({path:'output/playwright/hansen/boot-auth.png'})
  await page.locator('#boot-intro[data-phase="scan"]').waitFor()
  await page.waitForTimeout(1500)
  await page.screenshot({path:'output/playwright/hansen/boot-scan.png'})
  await page.locator('#boot-intro[data-phase="welcome"]').waitFor()
  await page.waitForTimeout(2400)
  await page.screenshot({path:'output/playwright/hansen/boot-welcome.png'})
  await page.locator('#home[data-ready="true"]').waitFor()
  check(!await page.locator('#boot-intro').isVisible(),'Natural opening reaches homepage')
  check(await page.locator('#home').getAttribute('inert')===null,'Homepage input restored')
  await page.getByRole('button',{name:'重播开场',exact:true}).click()
  await page.locator('#boot-intro[data-phase="access"]').waitFor()
  check(await page.locator('#home').getAttribute('inert')!==null,'Replay isolates input')
  await page.keyboard.press('Escape')
  await page.locator('#home[data-ready="true"]').waitFor()
  check(!await page.locator('#boot-intro').isVisible(),'Escape skips replay')
  check(await page.evaluate(()=>document.activeElement.matches('.wordmark')),'Skip restores focus')
  await page.goto('http://127.0.0.1:5175/#post/neko-rag')
  await page.locator('#reader').waitFor({state:'visible'})
  check(!await page.locator('#boot-intro').isVisible(),'Article deep link bypasses opening')
  await page.reload()
  await page.locator('#reader').waitFor({state:'visible'})
  check(!await page.locator('#boot-intro').isVisible(),'Article refresh bypasses opening')
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.goto('http://127.0.0.1:5175/')
  await page.locator('#home[data-ready="true"]').waitFor()
  check(!await page.locator('#boot-intro').isVisible(),'Reduced motion enters without animated sequence')
  check(await page.locator('#motion').getAttribute('aria-pressed')==='false','Reduced motion preference retained')
  await page.emulateMedia({reducedMotion:'no-preference'})
  for(const viewport of [{width:390,height:844},{width:320,height:700},{width:844,height:390}]){
    await page.setViewportSize(viewport)
    await page.getByRole('button',{name:'重播开场',exact:true}).click()
    await page.locator('#boot-intro:not([hidden])').waitFor()
    const bounds = await page.evaluate(()=>{
      const nav=document.querySelector('.intro-controls nav').getBoundingClientRect()
      const stage=document.querySelector('.intro-stage').getBoundingClientRect()
      return {nav:[nav.left,nav.top,nav.right,nav.bottom],stage:[stage.left,stage.top,stage.right,stage.bottom],w:innerWidth,h:innerHeight,overflow:document.documentElement.scrollWidth>innerWidth}
    })
    check(!bounds.overflow && bounds.nav[0]>=0 && bounds.nav[2]<=bounds.w && bounds.nav[3]<=bounds.h,`Opening controls fit ${viewport.width}x${viewport.height}`)
    check(bounds.stage[0]>=-1&&bounds.stage[2]<=bounds.w+1&&bounds.stage[1]>=-1&&bounds.stage[3]<=bounds.h+1,`Full composition fits ${viewport.width}x${viewport.height}`)
    await page.getByRole('button',{name:'先浏览文章目录',exact:true}).click()
    await page.getByRole('dialog',{name:/文章目录/}).waitFor()
    await page.getByRole('searchbox',{name:'搜索文章'}).fill('Neko')
    check(await page.locator('.result').count()===1,`Early directory remains usable ${viewport.width}x${viewport.height}`)
    await page.keyboard.press('Escape')
    await page.locator('#home:not([inert])').waitFor()
  }
  check(errors.length===0,'No JavaScript errors')
  return {checks,errors}
}
