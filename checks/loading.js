async (page) => {
  const checks = [], errors = []
  const check=(condition,name)=>{if(!condition)throw Error(name);checks.push(name)}
  page.on('pageerror',error=>errors.push(String(error)))
  await page.emulateMedia({reducedMotion:'no-preference'})
  await page.setViewportSize({width:1600,height:900})
  let release
  const pending=new Promise(resolve=>release=resolve)
  await page.route('**/assets/archive-cassette.glb',async route=>{await pending;await route.continue()})
  await page.goto('http://127.0.0.1:5175/?profile=1')
  await page.locator('#boot-intro[data-phase="waiting"]').waitFor({timeout:30000})
  check(await page.locator('#home').getAttribute('data-ready')!=='true','Natural welcome waits for real scene resources')
  check(await page.locator('#home').getAttribute('inert')!==null,'Slow scene does not expose home input')
  check(await page.locator('.intro-company').evaluate(el=>Number(getComputedStyle(el).opacity))>0,'Slow loading holds a visible welcome')
  await page.getByRole('button',{name:'跳过开场',exact:false}).click()
  check(await page.locator('#boot-intro').isVisible(),'Skip does not falsely mark pending resources ready')
  await page.getByRole('button',{name:'先浏览文章目录',exact:true}).click()
  await page.getByRole('dialog',{name:/文章目录/}).waitFor()
  await page.getByRole('searchbox',{name:'搜索文章'}).fill('玻璃')
  check(await page.locator('.result').count()===1,'Articles are searchable before scene loads')
  await page.locator('.result').click()
  await page.locator('#reader').waitFor({state:'visible'})
  check(!await page.locator('#boot-intro').isVisible(),'Early reading dismisses opening')
  release()
  await page.locator('#home[data-ready="true"]').waitFor()
  check(await page.locator('#reader').isVisible(),'Late scene load does not interrupt reader')
  await page.unroute('**/assets/archive-cassette.glb')
  await page.route('**/assets/archive-cassette.glb',route=>route.abort('failed'))
  await page.goto('http://127.0.0.1:5175/')
  await page.locator('#boot-intro[data-resources="failed"]').waitFor()
  check(await page.getByRole('button',{name:'重新载入',exact:true}).isVisible(),'Scene failure offers retry')
  await page.getByRole('button',{name:'进入文章目录',exact:false}).click()
  await page.getByRole('dialog',{name:/文章目录/}).waitFor()
  await page.locator('.result').first().click()
  await page.locator('#reader').waitFor({state:'visible'})
  check(await page.locator('#article h1').isVisible(),'Scene failure preserves article reading')
  await page.unroute('**/assets/archive-cassette.glb')
  await page.goto('http://127.0.0.1:5175/')
  await page.locator('#boot-intro[data-phase="access"]').waitFor()
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.locator('#home[data-ready="true"]').waitFor()
  check(!await page.locator('#boot-intro').isVisible(),'Changing reduced-motion preference completes loading without sequence')
  check(errors.length===0,'No uncaught errors across delayed/failed loads')
  return {checks,errors}
}
