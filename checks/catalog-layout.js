async(page)=>{
 const checks=[],bounds=[]
 const check=(value,name)=>{if(!value)throw Error(name);checks.push(name)}
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.setViewportSize({width:1600,height:900})
 await page.goto('http://127.0.0.1:5175/')
 await page.locator('#home[data-ready="true"]').waitFor()
 await page.evaluate(()=>document.fonts.ready)
 await page.screenshot({path:'output/playwright/hansen/catalog-home.png'})
 await page.getByRole('button',{name:/文章目录/}).click()
 await page.locator('[data-catalog-collection="ai"]').click()
 check(await page.evaluate(()=>document.activeElement.dataset.catalogCollection)==='ai','Collection filter restores keyboard focus')
 await page.getByRole('button',{name:'清除所有筛选',exact:true}).click()
 const scrolls=await page.evaluate(()=>({side:document.querySelector('.catalog-sidebar').scrollTop,main:document.querySelector('.catalog-main').scrollTop,focus:document.activeElement.id}))
 check(scrolls.side===0&&scrolls.main===0&&scrolls.focus==='search','Reset restores top of both panels and search focus')
 await page.screenshot({path:'output/playwright/hansen/catalog-index.png'})
 await page.getByRole('combobox',{name:'文章排序'}).selectOption('oldest')
 check((await page.locator('.result').first().getAttribute('href')).includes('transformer'),'Oldest-first sorting works')
 await page.keyboard.press('Escape')
 // The same article has two independent appearances but one canonical reader route.
 await page.getByRole('button',{name:'下一分类',exact:true}).click()
 await page.getByRole('button',{name:'下一分类',exact:true}).click()
 check(await page.locator('#home').getAttribute('data-collection')==='ai','AI collection selected')
 await page.locator('[data-row="0"]').click()
 await page.getByRole('link',{name:'打开这份记录'}).click()
 await page.locator('#reader').waitFor({state:'visible'})
 const canonical=page.url()
 check(canonical.endsWith('#post/neko-rag'),'AI appearance opens canonical Neko route')
 await page.keyboard.press('Escape')
 await page.getByRole('button',{name:'上一分类',exact:true}).click()
 await page.getByRole('button',{name:'上一分类',exact:true}).click()
 await page.locator('[data-row="0"]').click()
 await page.getByRole('link',{name:'打开这份记录'}).click()
 await page.locator('#reader').waitFor({state:'visible'})
 check(page.url()===canonical&&await page.locator('#home').getAttribute('data-collection')==='projects','Projects appearance retains context with the same Neko route')
 await page.keyboard.press('Escape')
 await page.getByRole('button',{name:'上一分类',exact:true}).click()
 check(await page.locator('#home').getAttribute('data-collection')==='research','Paper collection selected')
 await page.locator('[data-row="0"]').click()
 for(const viewport of [{width:1600,height:900},{width:1280,height:720},{width:390,height:844},{width:320,height:700},{width:844,height:390}]){
  await page.setViewportSize(viewport)
  const b=await page.evaluate(()=>{const r=selector=>{const b=document.querySelector(selector).getBoundingClientRect();return {left:b.left,right:b.right,top:b.top,bottom:b.bottom}};return {viewport:[innerWidth,innerHeight],title:r('#post-title'),selection:r('.selection'),read:r('#read'),nav:r('.lane-controls'),header:r('.masthead'),pageWidth:document.documentElement.scrollWidth}})
  bounds.push(b)
  check(b.pageWidth<=viewport.width+1&&b.title.right<=b.selection.right+1&&b.title.left>=0,`Long paper title fits ${viewport.width}x${viewport.height}`)
  if(viewport.width===844||viewport.width===320)await page.screenshot({path:`output/playwright/hansen/catalog-paper-${viewport.width}.png`})
 }
 await page.setViewportSize({width:1600,height:900})
 return {checks,scrolls,bounds}
}
