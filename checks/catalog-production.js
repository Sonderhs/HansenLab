async(page)=>{
 const checks=[],errors=[],failed=[]
 const check=(value,name)=>{if(!value)throw Error(name);checks.push(name)}
 page.on('pageerror',e=>errors.push(String(e)))
 page.on('response',r=>{if(r.url().startsWith('http://127.0.0.1:4185/')&&r.status()>=400)failed.push(r.url())})
 await page.emulateMedia({reducedMotion:'no-preference'})
 await page.setViewportSize({width:1600,height:900})
 await page.goto('http://127.0.0.1:4185/?profile=1')
 await page.locator('#boot-intro').waitFor({state:'attached'})
 await page.locator('[data-intro-skip]').click()
 await page.locator('#home[data-ready="true"]').waitFor()
 await page.evaluate(()=>document.fonts.ready)
 await page.locator('.masthead').click({position:{x:650,y:10}})
 await page.waitForTimeout(900)
 await page.screenshot({path:'output/playwright/hansen/catalog-home-final.png'})
 check(await page.evaluate(()=>typeof window.hansenProfile)==='undefined','Production probe is absent')
 await page.getByRole('button',{name:/文章目录/}).click()
 check(await page.locator('.result').count()===18,'Production contains only the selected 18 articles')
 await page.locator('.catalog-tabs').click({position:{x:650,y:10}})
 await page.screenshot({path:'output/playwright/hansen/catalog-final.png'})
 await page.getByRole('combobox',{name:'按原分类筛选'}).selectOption('Go')
 check(await page.locator('.result').count()===2,'Production category filter works')
 await page.getByRole('button',{name:'清除所有筛选',exact:true}).click()
 await page.locator('[data-catalog-view="series"]').click()
 check(await page.locator('.series-card').count()===6,'Production series catalog works')
 await page.locator('[data-catalog-series="clickhouse"]').click()
 await page.locator('.result').first().click()
 await page.locator('#reader').waitFor({state:'visible'})
 check(await page.locator('.excerpt-note').isVisible()&&await page.locator('.reader-series').isVisible(),'Production reader shows excerpt and series navigation')
 await page.goto('http://127.0.0.1:4185/#post/neko-rag')
 await page.locator('#reader').waitFor({state:'visible'})
 check(!await page.locator('#boot-intro').isVisible(),'Selected article deep link bypasses opening')
 check(errors.length===0&&failed.length===0,'No JavaScript errors or failed production requests')
 return {checks,errors,failed}
}
